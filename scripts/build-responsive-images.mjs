// Rebuild committed image variants with ImageMagick 7: node scripts/build-responsive-images.mjs
// Originals remain untouched and are used by the full-image viewer.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';

process.chdir(new URL('..', import.meta.url).pathname);
const manifest = {};
for (const folder of ['museum', 'works', 'explore', 'architecture']) {
  const outputDir = `assets/responsive/${folder}`;
  fs.mkdirSync(outputDir, {recursive: true});
  for (const file of fs.readdirSync(`assets/${folder}`).filter(file => /\.(jpg|png|webp)$/i.test(file)).sort()) {
    const source = `assets/${folder}/${file}`;
    const [width, height] = execFileSync('magick', ['identify', '-format', '%w %h', source], {encoding:'utf8'}).trim().split(' ').map(Number);
    const widths = folder === 'architecture' ? [768] : [...new Set([Math.min(480, width), Math.min(960, width)])];
    const variants = widths.map(size => {
      const output = `${outputDir}/${path.parse(file).name}-${size}.webp`;
      execFileSync('magick', [source, '-resize', `${size}x>`, '-quality', '82', output]);
      return [output, size];
    });
    if (folder === 'architecture') variants.push([source, width]);
    manifest[source] = {width, height, variants};
  }
}
const helpers = `
// Sizes describe the rendered image, letting the browser choose for screen density.
window.responsiveImageAttributes = (source, sizes) => {
  const item = window.responsiveImages[source];
  if (!item) return 'src="' + source + '"';
  return 'src="' + item.variants[0][0] + '" srcset="' + item.variants.map(([url, width]) => url + ' ' + width + 'w').join(', ') + '" sizes="' + sizes + '" width="' + item.width + '" height="' + item.height + '"';
};
window.setResponsiveImage = (image, source, sizes) => {
  const item = window.responsiveImages[source];
  if (item) {
    image.sizes = sizes;
    image.srcset = item.variants.map(([url, width]) => url + ' ' + width + 'w').join(', ');
    image.width = item.width;
    image.height = item.height;
  }
  image.src = item?.variants[0][0] || source;
};
`;
fs.writeFileSync('js/responsive-images.js', `/* Generated by scripts/build-responsive-images.mjs. */\nwindow.responsiveImages = ${JSON.stringify(manifest)};\n${helpers}`);
// Keep the homepage fully usable without JavaScript and without loading originals first.
const context = {window:{}};
vm.runInNewContext(helpers, context);
context.window.responsiveImages = manifest;
const home = fs.readFileSync('index.html', 'utf8').replace(/<img\b[^>]*>/g, tag => {
  const source = tag.match(/(?:data-image-source|src)="([^"]+)"/)?.[1];
  if (!manifest[source]) return tag;
  const sizes = tag.includes('card-architecture') ? '(max-width: 760px) 40vw, 50vw' : '(max-width: 760px) 24vw, 30vw';
  const clean = tag.replace(/\s(?:data-image-source|src|srcset|sizes|width|height)="[^"]*"/g, '');
  return clean.replace('<img', `<img data-image-source="${source}" ${context.window.responsiveImageAttributes(source, sizes)}`);
});
fs.writeFileSync('index.html', home);
const eras = Object.keys(manifest).filter(source => source.startsWith('assets/architecture/')).map(source => path.parse(source).name);
fs.writeFileSync('css/responsive-images.css', `/* Generated by scripts/build-responsive-images.mjs. */\n@media (max-width: 760px) {\n${eras.map(era => `  [data-era='${era}'], .chapter-card.${era} { --architecture: url('../assets/responsive/architecture/${era}-768.webp'); }`).join('\n')}\n${['medieval','ancient','impressionism'].map(era => `  .cover-${era}::before { background-image: url('../assets/responsive/architecture/${era}-768.webp'); }`).join('\n')}\n}\n`);
console.log(`Generated responsive variants for ${Object.keys(manifest).length} images.`);
